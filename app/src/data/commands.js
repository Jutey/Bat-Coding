export function getCommandsForLesson(lessonNum) {
  return COMMANDS.filter(c => c.lesson <= lessonNum);
}

export function findCommand(typed) {
  const clean = typed.trim().toLowerCase().replace('@', '');
  return COMMANDS.find(c =>
    c.cmd.toLowerCase().replace('@', '').startsWith(clean) ||
    clean.startsWith(c.cmd.toLowerCase().replace('@', ''))
  );
}
